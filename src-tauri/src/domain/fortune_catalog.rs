fn grade_for_number(number: usize) -> &'static str {
    let rank = ((number - 1) * 37) % FORTUNE_COUNT;
    match rank {
        0..=5 => "上上签",
        6..=21 => "上签",
        22..=41 => "中上签",
        42..=66 => "中签",
        67..=81 => "中下签",
        82..=97 => "下签",
        _ => "下下签",
    }
}

pub fn fortune_by_index(index: usize, date: &str) -> DailyFortune {
    let catalog_index = index % FORTUNE_COUNT;
    let number = catalog_index + 1;
    let definition = FORTUNES[catalog_index];
    DailyFortune {
        id: format!("fortune-{date}-{number:03}"),
        date: date.into(),
        number: number as i32,
        catalog: CATALOG_NAME.into(),
        grade: grade_for_number(number).into(),
        title: definition.title.into(),
        verse: definition.verse.into(),
        interpretation: definition.interpretation.into(),
        advice: definition.advice.into(),
    }
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;

    #[test]
    fn catalog_contains_one_hundred_unique_fortunes() {
        assert_eq!(FORTUNES.len(), FORTUNE_COUNT);
        assert_eq!(
            FORTUNES
                .iter()
                .map(|fortune| fortune.title)
                .collect::<HashSet<_>>()
                .len(),
            FORTUNE_COUNT
        );
        assert_eq!(
            FORTUNES
                .iter()
                .map(|fortune| fortune.verse)
                .collect::<HashSet<_>>()
                .len(),
            FORTUNE_COUNT
        );
        assert_eq!(
            FORTUNES
                .iter()
                .map(|fortune| fortune.interpretation)
                .collect::<HashSet<_>>()
                .len(),
            FORTUNE_COUNT
        );
        assert_eq!(
            FORTUNES
                .iter()
                .map(|fortune| fortune.advice)
                .collect::<HashSet<_>>()
                .len(),
            FORTUNE_COUNT
        );
    }

    #[test]
    fn grade_distribution_matches_the_design() {
        let grades = (1..=FORTUNE_COUNT).map(grade_for_number).fold(
            std::collections::HashMap::new(),
            |mut counts, grade| {
                *counts.entry(grade).or_insert(0) += 1;
                counts
            },
        );
        assert_eq!(grades.get("上上签"), Some(&6));
        assert_eq!(grades.get("上签"), Some(&16));
        assert_eq!(grades.get("中上签"), Some(&20));
        assert_eq!(grades.get("中签"), Some(&25));
        assert_eq!(grades.get("中下签"), Some(&15));
        assert_eq!(grades.get("下签"), Some(&16));
        assert_eq!(grades.get("下下签"), Some(&2));
    }

    #[test]
    fn out_of_range_index_wraps_to_the_catalog() {
        let first = fortune_by_index(0, "2026-07-23");
        let wrapped = fortune_by_index(100, "2026-07-23");
        assert_eq!(first.number, 1);
        assert_eq!(wrapped.number, 1);
        assert_eq!(first.title, wrapped.title);
    }
}
